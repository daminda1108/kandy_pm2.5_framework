"""verify_report.py -- a verification report for the built thesis (second external review, item 12).

Lists, for the claims the built thesis actually cites: the source artefact each was computed from, whether
that artefact is present locally, whether it is tracked in the public repository, and the input family it
rests on (and so whether an outside reader can regenerate it from public inputs alone). It records the git
commit and the claims-generation date. It does not re-run the analyses; the build's claims gate already
refuses to build when a stored value and a recomputation disagree.

Usage: python build/verify_report.py --thesis a
Out:   VERIFICATION_thesis_<id>.md at the repository root
"""
from __future__ import annotations

import argparse
import io
import json
import os
import re
import subprocess
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent                                   # D:/ProjectCD
CLAIMS = ROOT / "kandy_pm25" / "data" / "processed" / "modular" / "claims.json"

# Input family by source-artefact name. Access: "public" = obtainable without agreement;
# "restricted" = needs an API key, an institutional agreement, or is a published value transcribed.
FAMILIES = [
    (r"^(kandy_|rh_|f_sensitivity|nbro|exposure|health|decomp|T_|partition|kandy_partition|field|summary_v3|"
     r"predictions_|gauge|srep|kandy_field|kandy_contrast|species_partition|chemistry|F_spatiotemporal|F_cycles|"
     r"F_episode|F_field|S_traffic|S_emit|shipped field|elangasinghe|vandonkelaar|dilution|blh)",
     "Kandy chain (low-cost sensor record via PurpleAir API; satellite, reanalysis, composition model)", "restricted"),
    (r"^(ladder|confirm|review_|fullnet|kandy_model|learners|rich|bud0|cluster|loss_|precip|order|ladder_v2|"
     r"independent_background|c1_satellite|global_reference|maiac|ghap|station_count|colombo|donor|step|band|frame|"
     r"coastal|instrument|coverage|p4_)",
     "cross-city ladder (OpenAQ public archive, CNEMC public archive, ERA5, MAIAC, OSM, GEE layers)", "public"),
    (r"^(spatial_curve|reanalysis|x5|satellite_benchmark|tour|phase|r2|s1|s2|null|emb|lur|subgrid|site|"
     r"validation_scorecard|scorecard|ktm|r2b|spatial_tournament|siting|F8_kathmandu|reviewer_response|multicity)",
     "spatial tests and analogue cities (public monitoring archives, OSM, GEE layers)", "public"),
    (r"^(registrations|meta|thesis)", "document metadata and the registration registry", "public"),
]


def family(src: str):
    name = Path(src.split(" ")[-1]).name if " vs " not in src else Path(src.split(" vs ")[0]).name
    for pat, fam, acc in FAMILIES:
        if re.search(pat, name) or re.search(pat, src):
            return fam, acc
    return "other (see the source file's generating script)", "unclassified"


def tracked(paths):
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "ls-files"], capture_output=True, text=True).stdout
    except Exception:                                                        # noqa: BLE001
        return set()
    names = {Path(p).name for p in out.splitlines()}
    return {p for p in paths if Path(p).name in names}


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--thesis", default="a"); a = ap.parse_args()
    built = HERE / a.thesis / "thesis.md"
    meta = json.load(open(HERE / a.thesis / "meta.json", encoding="utf-8"))
    src_text = "".join(io.open(p, encoding="utf-8").read()
                       for p in list((HERE.parent / "pool").rglob("*.md")) + list((HERE.parent / "theses" / a.thesis).rglob("*.md"))
                       + list((HERE.parent / "thesis" / "tables").glob("*.md")))
    cited = set(re.findall(r"\{\{claim:([^}\s]+)\}\}", src_text))
    C = json.load(open(CLAIMS, encoding="utf-8"))
    claims = C["claims"]
    used = {k: v for k, v in claims.items() if k in cited}
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    by_src = defaultdict(list)
    for k, v in used.items():
        by_src[v.get("source", "unknown") if isinstance(v, dict) else "unknown"].append(k)
    tr = tracked(by_src)
    fam_count, acc_count = Counter(), Counter()
    rows = []
    for src, ks in sorted(by_src.items(), key=lambda x: -len(x[1])):
        fam, acc = family(src)
        fam_count[fam] += len(ks); acc_count[acc] += len(ks)
        rows.append(f"| `{src}` | {len(ks)} | {'yes' if src in tr else 'no (derived data, regenerated by its script)'} | {fam} | {acc} |")
    out = ROOT / f"VERIFICATION_thesis_{a.thesis}.md"
    lines = [f"# Verification report, thesis {a.thesis.upper()}", "",
             f"- Built: {meta.get('built')}  ·  repository commit at report time: `{commit}`",
             f"- Claims generated: {C.get('generated')}  ·  claims in the registry: {len(claims)}  ·  cited by this thesis: {len(used)}",
             f"- Claims cited but missing from the registry: {len(cited - set(claims))}",
             "- Every cited claim was recomputed and compared at build time; the build refuses on any drift.",
             "", "## By input access", "",
             "| access | claims |", "|---|---:|"] + [f"| {k} | {v} |" for k, v in acc_count.most_common()] + [
             "", "`public`: regenerable from openly available inputs with the scripts in this repository. "
             "`restricted`: rests on the Kandy low-cost sensor record (PurpleAir API access) or published values; "
             "an authorised reader can regenerate it after obtaining those inputs (see THESIS_REPRODUCTION.md).",
             "", "## By input family", "", "| family | claims |", "|---|---:|"] + \
            [f"| {k} | {v} |" for k, v in fam_count.most_common()] + [
             "", "## By source artefact", "",
             "| source artefact | claims | tracked in the repository | input family | access |",
             "|---|---:|---|---|---|"] + rows + [
             "", "Independent reproduction by a third party has not yet been carried out."]
    tmp = out.with_suffix(".tmp.md")
    io.open(tmp, "w", encoding="utf-8").write("\n".join(lines) + "\n"); os.replace(tmp, out)
    print(f"cited {len(used)} claims from {len(by_src)} artefacts; access {dict(acc_count)} -> {out}")


if __name__ == "__main__":
    main()
