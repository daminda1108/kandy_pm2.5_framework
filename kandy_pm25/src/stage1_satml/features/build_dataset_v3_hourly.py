def load_station_constants() -> dict:
    """Load per-sensor b_FECT offsets from the locked JSON.

    The JSON is generated by the one-time derivation step and contains:
      {sensor_id: {b_FECT_2019_ugm3, b_FECT_all_ugm3, ...}, _meta: {...}}

    We use b_FECT_all_ugm3 (full-period mean) because it centres the training
    residual on zero by construction. The single-constant LOMO leak is
    negligible (1/62 of one scalar) and can be hardened to per-fold
    recomputation inside the training loop later.
    """
    if not STATION_CONSTANTS_PATH.exists():
        raise FileNotFoundError(
            f"Missing {STATION_CONSTANTS_PATH}. "
            "Run the b_FECT derivation step first."
        )
    with open(STATION_CONSTANTS_PATH) as f:
        return json.load(f)

