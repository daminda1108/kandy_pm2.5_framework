# 3. Calendar / time-harmonic / solar geometry features
# ════════════════════════════════════════════════════════════════════════════
def add_calendar_features(df: pd.DataFrame) -> pd.DataFrame:
    """Adds hour_of_day, dow, doy harmonic encodings + solar zenith angle."""
    t = df["datetime_utc"]
    hod = t.dt.hour + t.dt.minute / 60.0
    df["hour_of_day_sin"] = np.sin(2 * np.pi * hod / 24)
    df["hour_of_day_cos"] = np.cos(2 * np.pi * hod / 24)

    dow = t.dt.dayofweek  # Mon=0, Sun=6
    df["dow_sin"] = np.sin(2 * np.pi * dow / 7)
    df["dow_cos"] = np.cos(2 * np.pi * dow / 7)

    doy = t.dt.dayofyear
    df["doy_sin"] = np.sin(2 * np.pi * doy / 365.25)
    df["doy_cos"] = np.cos(2 * np.pi * doy / 365.25)

    # Solar zenith angle (approximate; NOAA formula)
    df["solar_zenith_angle"] = _solar_zenith(df)
    df["daylight_phase"] = np.clip(np.cos(np.radians(df["solar_zenith_angle"])), 0, 1)
    return df


def _solar_zenith(df: pd.DataFrame) -> pd.Series:
    """Compute solar zenith angle in degrees per row. Vectorised."""
    t = df["datetime_utc"]
    lat = df["lat"].values
    lon = df["lon"].values

    doy = t.dt.dayofyear.values
    hod = t.dt.hour.values + t.dt.minute.values / 60.0

    # Solar declination (Cooper 1969 approx.)
    decl = 23.45 * np.sin(np.radians(360.0 * (284 + doy) / 365.0))
    decl_rad = np.radians(decl)

    # Solar hour angle (local solar time approximated by UTC + lon/15)
    lst = hod + lon / 15.0
    hour_angle = np.radians(15.0 * (lst - 12.0))

    lat_rad = np.radians(lat)
    cos_sza = (np.sin(lat_rad) * np.sin(decl_rad)
               + np.cos(lat_rad) * np.cos(decl_rad) * np.cos(hour_angle))
    cos_sza = np.clip(cos_sza, -1, 1)
    sza_deg = np.degrees(np.arccos(cos_sza))
    return pd.Series(sza_deg, index=df.index)


# ════════════════════════════════════════════════════════════════════════════
# 4. Lags (hourly)
# ════════════════════════════════════════════════════════════════════════════
def add_hourly_lags(df: pd.DataFrame) -> pd.DataFrame:
    """Adds lag_1h, lag_3h, lag_24h, lag_168h per sensor.

    df must be sorted by (sensor_id, datetime_utc).
    """
    df = df.sort_values(["sensor_id", "datetime_utc"]).reset_index(drop=True)
    g = df.groupby("sensor_id")["pm25_observed"]
    for h in (1, 3, 24, 168):
        df[f"lag_{h}h"] = g.shift(h)
    return df


