# ════════════════════════════════════════════════════════════════════════════
TIER_C_DIR = ROOT / "data" / "external" / "tier_c"


def load_era5_winds_temp_precip_hourly() -> Optional[pd.DataFrame]:
    """Load and merge the existing tier_c GEE-exported ERA5 hourly CSVs.

    Sources:
      data/external/tier_c/era5_land/era5_land_{year}.csv
        — u10, v10, total_precipitation_hourly
      data/external/tier_c/era5_t2m/era5_t2m_{year}.csv
        — temperature_2m, dewpoint_temperature_2m

    Notes:
      - GEE ERA5 hourly is on the single-level catalogue (no t925 pressure
        level). t925_minus_t2m_04LT_yesterday is therefore deferred to a
        separate CDS-API pull or dropped.
      - Surface solar radiation (ssr) is added by a separate GEE export
        (KandyV3_Data folder; see scripts/gee_export_v3_missing.py) and
        merged separately once downloaded.
    """
    land_dir = TIER_C_DIR / "era5_land"
    t2m_dir = TIER_C_DIR / "era5_t2m"
    ssr_dir = TIER_C_DIR / "era5_ssr"  # populated post-GEE download

    if not land_dir.exists() and not t2m_dir.exists():
        log.warning(f"ERA5 tier_c dirs missing: {land_dir}, {t2m_dir}")
        return None

    def _concat(dirpath: Path, prefix: str) -> Optional[pd.DataFrame]:
        if not dirpath.exists():
            return None
        files = sorted(dirpath.glob(f"{prefix}_*.csv"))
        if not files:
            return None
        return pd.concat([pd.read_csv(p) for p in files], ignore_index=True)

    land = _concat(land_dir, "era5_land")
    t2m = _concat(t2m_dir, "era5_t2m")
    ssr = _concat(ssr_dir, "era5_ssr")

    if land is None and t2m is None:
        return None

    base = None
    for d in (land, t2m, ssr):
        if d is None:
            continue
        d["datetime_utc"] = pd.to_datetime(d["datetime"], utc=True)
        d = d.drop(columns=["datetime"]).drop_duplicates("datetime_utc")
        base = d if base is None else base.merge(d, on="datetime_utc", how="outer")

    base = base.sort_values("datetime_utc").reset_index(drop=True)
    # Rename to short, builder-friendly names
    rename = {
        "u_component_of_wind_10m": "u10",
        "v_component_of_wind_10m": "v10",
        "total_precipitation_hourly": "tp",
        "temperature_2m": "t2m",
        "dewpoint_temperature_2m": "d2m",
        "surface_solar_radiation_downwards_sum": "ssr",
    }
    base = base.rename(columns=rename)

    # Derived: wind speed + direction (atan2 for wind direction from u,v)
    if "u10" in base.columns and "v10" in base.columns:
        base["wind_speed_10m"] = np.sqrt(base["u10"]**2 + base["v10"]**2)
        base["wind_dir_10m"] = (
            np.degrees(np.arctan2(-base["u10"], -base["v10"])) % 360
        )
    # Derived: dewpoint depression (kelvin difference)
    if "t2m" in base.columns and "d2m" in base.columns:
        base["dewpoint_depression"] = base["t2m"] - base["d2m"]

    log.info(f"ERA5 winds+temp+precip merged: {len(base):,} rows; "
             f"cols={[c for c in base.columns if c != 'datetime_utc']}")
    return base


