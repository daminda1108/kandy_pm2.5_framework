# 5. ERA5 hourly BLH merge
# ════════════════════════════════════════════════════════════════════════════
def load_era5_blh_hourly() -> Optional[pd.DataFrame]:
    if not ERA5_BLH_HOURLY.exists():
        log.warning(f"ERA5 BLH hourly missing: {ERA5_BLH_HOURLY}")
        return None
    df = pd.read_parquet(ERA5_BLH_HOURLY)
    # expected schema: datetime_utc, blh_m (units: metres)
    cols = list(df.columns)
    if "datetime_utc" not in cols:
        # try common aliases
        for alias in ("datetime", "time", "valid_time"):
            if alias in cols:
                df = df.rename(columns={alias: "datetime_utc"})
                break
    df["datetime_utc"] = pd.to_datetime(df["datetime_utc"], utc=True)
    if "blh_m" not in df.columns and "blh" in df.columns:
        df = df.rename(columns={"blh": "blh_m"})
    log.info(f"ERA5 BLH hourly: {len(df):,} rows")
    return df[["datetime_utc", "blh_m"]]


