# 11. Pre-dawn BL stability (T925 − T2m @ 04 LT yesterday)
# ════════════════════════════════════════════════════════════════════════════
def add_predawn_stability(df: pd.DataFrame,
                          t925_df: Optional[pd.DataFrame]) -> pd.DataFrame:
    """Merge hourly `t925_K` and compute `t925_minus_t2m_04LT_yesterday`.

    The 04 LT proxy is the subsidence-inversion gauge for Kandy mornings:
    a positive value (warm 925 hPa air above cool 2 m valley air) indicates
    a stable nocturnal layer that traps emissions through sunrise. Requires
    `t2m` to already be in `df` (merged via era5_full upstream).
    """
    if t925_df is None:
        df["t925_K"] = np.nan
        df["t925_minus_t2m_04LT_yesterday"] = np.nan
        return df

    df = df.merge(t925_df, on="datetime_utc", how="left")

    if "t2m" not in df.columns:
        log.warning("t2m absent — t925_minus_t2m_04LT_yesterday set to NaN")
        df["t925_minus_t2m_04LT_yesterday"] = np.nan
        return df

    lt_offset_h = KANDY_LON / 15.0  # ≈ +5.376 h
    work = df[["datetime_utc", "t925_K", "t2m"]].drop_duplicates(
        "datetime_utc").copy()
    work["local_dt"] = work["datetime_utc"] + pd.Timedelta(hours=lt_offset_h)
    work["local_hour"] = work["local_dt"].dt.hour
    sel = work[work["local_hour"] == 4].copy()
    sel["local_date"] = sel["local_dt"].dt.date
    sel["stability"] = sel["t925_K"] - sel["t2m"]
    daily = (sel.groupby("local_date")["stability"].mean()
                .reset_index()
                .rename(columns={"local_date": "_yest",
                                 "stability":
                                 "t925_minus_t2m_04LT_yesterday"}))

    local_dt = df["datetime_utc"] + pd.Timedelta(hours=lt_offset_h)
    df["_yest"] = (local_dt - pd.Timedelta(days=1)).dt.date
    df = df.merge(daily, on="_yest", how="left")
    df.drop(columns=["_yest"], inplace=True)
    return df


