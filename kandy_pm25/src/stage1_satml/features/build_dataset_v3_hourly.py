# Main orchestrator
# ════════════════════════════════════════════════════════════════════════════
STAGE_LIST = [
    "labels", "c_prior", "calendar", "lags",
    "era5_blh", "era5_full", "cams", "maiac",
    "tropomi", "viirs_fires", "predawn",
    "ssr_v3", "no2_v3",
]


def build(stages: Optional[list[str]] = None, dry_run: bool = False
          ) -> Optional[pd.DataFrame]:
    stages = stages or STAGE_LIST
    log.info(f"Build stages requested: {stages}")
    log.info(f"Dry-run mode: {dry_run}")

    # 1. labels
    if "labels" not in stages:
        log.error("'labels' is mandatory; aborting.")
        return None
    labels = load_fect_hourly_labels()

    # 2. c_prior
    geos = load_geos_cf_hourly() if "c_prior" in stages else None

    # 3. left-join everything onto labels
    df = labels.copy()
    if geos is not None:
        df = df.merge(geos, on="datetime_utc", how="left")

        # Apply per-sensor b_FECT offset to get the anchored prior
        # c_prior_anchored(t, sensor) = ρ · GEOS-CF(t) + b_FECT[sensor]
        consts = load_station_constants()
        b_map = {int(k): v["b_FECT_all_ugm3"]
                 for k, v in consts.items() if k.isdigit()}
        df["b_FECT"] = df["sensor_id"].map(b_map)
        if df["b_FECT"].isna().any():
            missing = df.loc[df["b_FECT"].isna(), "sensor_id"].unique().tolist()
            raise ValueError(f"Missing b_FECT for sensors {missing}; "
                             f"add to {STATION_CONSTANTS_PATH}")
        df["c_prior_anchored"] = df["c_prior_scaled"] + df["b_FECT"]
        df["residual_target"] = df["pm25_observed"] - df["c_prior_anchored"]
        n_nan = df["c_prior_scaled"].isna().sum()
        log.info(
            f"  c_prior merged + b_FECT applied: "
            f"{n_nan:,} rows lack GEOS-CF ({n_nan / len(df) * 100:.1f}%); "
            f"residual_mean = {df['residual_target'].mean():.3f} µg m⁻³ "
            f"(target |mean| < 0.5 per H8)"
        )
        for sid, b in b_map.items():
            log.info(f"    b_FECT[{sid}] = {b:+.4f} µg m⁻³")
    else:
        df["residual_target"] = df["pm25_observed"] - KOALA_ANCHOR_UG_M3
        log.warning("c_prior stage skipped — residual computed against "
                    f"KOALA constant {KOALA_ANCHOR_UG_M3:.2f}; not production")

    if "calendar" in stages:
        df = add_calendar_features(df)
        log.info("  calendar features added (hour/dow/doy + solar zenith)")
    if "lags" in stages:
        df = add_hourly_lags(df)
        log.info("  hourly lags (1h, 3h, 24h, 168h) added")

    if "era5_blh" in stages:
        blh = load_era5_blh_hourly()
        if blh is not None:
            df = df.merge(blh, on="datetime_utc", how="left")
            log.info("  ERA5 BLH merged")

    era5_full = None
    if "era5_full" in stages:
        era5_full = load_era5_winds_temp_precip_hourly()
        if era5_full is not None:
            df = df.merge(era5_full, on="datetime_utc", how="left")
            log.info(f"  ERA5 full hourly merged ({len(era5_full):,} rows)")

    if "cams" in stages:
        cams = load_cams_hourly_interpolated()
        if cams is not None:
            df = df.merge(cams, on="datetime_utc", how="left")
            log.info("  CAMS hourly (interpolated) merged")

    if "maiac" in stages:
        maiac = load_maiac_with_staleness()
        if maiac is not None:
            df = df.merge(maiac, on="datetime_utc", how="left")

    if "tropomi" in stages:
        tropomi = load_tropomi_with_staleness()
        if tropomi is not None:
            df = df.merge(tropomi, on="datetime_utc", how="left")

    if "viirs_fires" in stages:
        fires = load_viirs_fires_hourly()
        if fires is not None:
            df = df.merge(fires, on="datetime_utc", how="left")

    if "ssr_v3" in stages:
        ssr = load_ssr_hourly_v3()
        if ssr is not None:
            df = df.merge(ssr, on="datetime_utc", how="left")
            log.info("  ssr v3 hourly merged")

    if "no2_v3" in stages:
        no2 = load_tropomi_no2_v3()
        if no2 is not None:
            df = df.merge(no2, on="datetime_utc", how="left")
            # Derived: NO₂ column ÷ BLH = volume-mixing-ratio proxy
            if "blh_m" in df.columns:
                df["no2_blh_ratio"] = (
                    df["tropomi_no2_mol_m2"] / df["blh_m"]
                ).astype("float32")
            log.info("  TROPOMI NO₂ v3 hourly merged "
                     "(+ no2_blh_ratio derived)")

    if "predawn" in stages:
        # Predawn proxy now uses the dedicated t925 parquet (not era5_full)
        t925_df = load_t925_hourly_v3()
        df = add_predawn_stability(df, t925_df)
        log.info("  predawn stability (t925_K + 04LT-y proxy) added")

    # sanity counts
    log.info(f"Final shape: {df.shape}")
    log.info(f"Columns: {list(df.columns)}")
    log.info(f"NaN summary:")
    for c in df.columns:
        n_nan = df[c].isna().sum()
        if n_nan > 0:
            log.info(f"   {c}: {n_nan:,} NaN "
                     f"({n_nan / len(df) * 100:.1f}%)")

    if dry_run:
        log.info("[dry-run] not writing parquet")
        return df

    df.to_parquet(OUT_PATH, index=False)
    log.info(f"Wrote {OUT_PATH} ({df.shape[0]:,} rows × {df.shape[1]} cols)")

    return df


# ── stand-alone CLI ─────────────────────────────────────────────────────────
def main():
    p = argparse.ArgumentParser()
    p.add_argument("--build", action="store_true",
                   help="Run the build and write parquet")
    p.add_argument("--dry-run", action="store_true",
                   help="Inventory inputs, do not write parquet")
    p.add_argument("--stages", default="",
                   help=f"Comma-separated subset of: {','.join(STAGE_LIST)}")
    args = p.parse_args()

    if not (args.build or args.dry_run):
        p.print_help(); return

    stages = args.stages.split(",") if args.stages else None
    if stages:
        bad = [s for s in stages if s not in STAGE_LIST]
        if bad:
            log.error(f"Unknown stages: {bad}; valid = {STAGE_LIST}")
            return
    build(stages=stages, dry_run=args.dry_run and not args.build)


if __name__ == "__main__":
    main()
