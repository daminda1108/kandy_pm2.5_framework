# 2. c_prior — GEOS-CF hourly scaled by KANDY_GEOS_CF_RATIO
# ════════════════════════════════════════════════════════════════════════════
def load_geos_cf_hourly() -> pd.DataFrame:
    """Return GEOS-CF hourly with Option-B derivative features.

    Columns:
      geos_cf_pm25_raw                    — kept for c_prior derivation only;
                                            the LEVEL is dropped from X at
                                            training time.
      c_prior_scaled                      — used as baseline; not in X.
      geos_cf_dt_1h, geos_cf_dt_3h        — temporal derivatives (in X).
      geos_cf_anom_24h                    — anomaly vs 24-h rolling mean (in X).
      hours_since_geos_obs                — staleness (forward-fill flag, in X).
    """
    csvs = sorted(GEOS_CF_DIR.glob("kandy_geos_cf_*.csv"))
    if not csvs:
        raise FileNotFoundError(f"No GEOS-CF CSVs in {GEOS_CF_DIR}")
    dfs = [pd.read_csv(p) for p in csvs]
    df = pd.concat(dfs, ignore_index=True)
    df["datetime_utc"] = pd.to_datetime(df["datetime"], utc=True)
    df = df[["datetime_utc", "PM25_RH35_GCC"]].rename(
        columns={"PM25_RH35_GCC": "geos_cf_pm25_raw"}
    )
    df = df.drop_duplicates("datetime_utc").sort_values("datetime_utc")

    # Strict hourly grid + ffill ≤ 3 h
    df = df.set_index("datetime_utc")
    full_idx = pd.date_range(df.index.min(), df.index.max(),
                             freq="1h", tz="UTC")
    df = df.reindex(full_idx)
    obs_present = df["geos_cf_pm25_raw"].notna()
    df["hours_since_geos_obs"] = (
        (~obs_present).astype(int)
        .groupby(obs_present.cumsum()).cumsum()
    )
    df["geos_cf_pm25_raw"] = df["geos_cf_pm25_raw"].ffill(limit=3)

    df["c_prior_scaled"] = df["geos_cf_pm25_raw"] * KANDY_GEOS_CF_RATIO

    # Option B derivatives (kept in X; level dropped at training time)
    df["geos_cf_dt_1h"] = df["geos_cf_pm25_raw"].diff(1)
    df["geos_cf_dt_3h"] = df["geos_cf_pm25_raw"].diff(3)
    df["geos_cf_anom_24h"] = (
        df["geos_cf_pm25_raw"]
        - df["geos_cf_pm25_raw"].rolling(24, min_periods=12).mean()
    )

    df = df.reset_index().rename(columns={"index": "datetime_utc"})
    log.info(
        f"GEOS-CF hourly (Option B): {len(df):,} rows, "
        f"{df['datetime_utc'].min()} -> {df['datetime_utc'].max()}, "
        f"ratio rho={KANDY_GEOS_CF_RATIO:.4f}; "
        f"derivatives (dt_1h, dt_3h, anom_24h) + staleness added"
    )
    return df


