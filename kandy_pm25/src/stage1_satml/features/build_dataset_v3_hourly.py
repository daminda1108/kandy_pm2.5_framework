def load_tropomi_no2_v3() -> Optional[pd.DataFrame]:
    """Broadcast daily TROPOMI NO₂ overpass to hourly with staleness flag.

    TROPOMI overpass is ≈13:30 LT (≈08:00 UTC for Kandy). For each calendar day
    with a daily-mean retrieval, we stamp the value at 08:00 UTC of that day,
    then forward-fill up to 48 h with a `hours_since_no2_overpass` counter so
    the model can discount stale observations.
    """
    if not NO2_DAILY_V3.exists():
        log.warning(f"TROPOMI NO₂ v3 daily missing: {NO2_DAILY_V3}")
        return None
    daily = pd.read_parquet(NO2_DAILY_V3)
    daily["datetime_utc"] = (
        pd.to_datetime(daily["date"], utc=True) + pd.Timedelta(hours=8)
    )
    daily = daily[["datetime_utc", "tropomi_no2_mol_m2"]].dropna()

    full_idx = pd.date_range(
        daily["datetime_utc"].min(),
        daily["datetime_utc"].max() + pd.Timedelta(hours=23),
        freq="1h", tz="UTC",
    )
    out = pd.DataFrame({"datetime_utc": full_idx}).merge(
        daily, on="datetime_utc", how="left",
    )
    obs_present = out["tropomi_no2_mol_m2"].notna()
    out["hours_since_no2_overpass"] = (
        (~obs_present).astype(int)
        .groupby(obs_present.cumsum()).cumsum()
    )
    out["tropomi_no2_mol_m2"] = out["tropomi_no2_mol_m2"].ffill(limit=48)
    log.info(
        f"TROPOMI NO₂ v3 (hourly broadcast): {len(out):,} hourly rows, "
        f"frac_present={out['tropomi_no2_mol_m2'].notna().mean():.1%}"
    )
    return out


